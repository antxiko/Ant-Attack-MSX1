"""Build the experimental MSX1 64 KiB Ant Attack cartridge from the snapshot.

The MSX front end has menus, scoring and PSG playback of the original script
notes. Visual details and some original BASIC behaviour still differ.
The original .z80 file is never modified.
"""
from pathlib import Path
import hashlib
import re
import subprocess
import sys

from inspect_ant import load_snapshot

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src" / "msx"
OUT = ROOT / "build" / "Ant_Attack_MSX1_64K_render_fast.rom"
SNAP = ROOT / "JUEBOS" / "Ant_Attack_1983_Quicksilva.z80"
SNAP_SHA256 = "aad0783b2fe3274be1aaeb3587e26187cf61a2c62a3cd997618a427d9932f1cd"


def patch(ram: bytearray, address: int, before: bytes, after: bytes) -> None:
    if len(before) != len(after):
        raise ValueError(f"Patch at {address:04X} changes length")
    actual = bytes(ram[address:address + len(before)])
    if actual != before:
        raise ValueError(f"Patch at {address:04X}: expected {before.hex()}, got {actual.hex()}")
    ram[address:address + len(after)] = after


def assemble(source: str, binary: str, symbols: str) -> dict[str, int]:
    proc = subprocess.run(["pasmo", source, binary, symbols], cwd=SRC,
                          capture_output=True, text=True)
    if proc.returncode:
        raise RuntimeError(proc.stdout + proc.stderr)
    result = {}
    for line in (SRC / symbols).read_text().splitlines():
        match = re.match(r"(\w+)\s+EQU\s+0?([0-9A-F]+)H", line, re.I)
        if match:
            result[match.group(1)] = int(match.group(2), 16)
    return result


def main() -> None:
    subprocess.run([sys.executable, str(ROOT / "tools" / "gen_hud.py")], check=True)
    actual_hash = hashlib.sha256(SNAP.read_bytes()).hexdigest()
    if actual_hash != SNAP_SHA256:
        raise ValueError(f"Unexpected snapshot SHA256: {actual_hash}")
    memory, _ = load_snapshot()
    ram = bytearray(memory)
    # El original arranca la partida con DI. En MSX, el PSG necesita el VBlank
    # para terminar los efectos aunque el mapa tarde en dibujarse.
    patch(ram, 0x8000, b"\xf3", b"\xfb")
    # In the machine-code portion, translate Spectrum keyboard port reads.
    # The exact sites are checked so the script fails if the input differs.
    keyboard_reads = (0x800C, 0x8063, 0x807B, 0x8405,
                      0x8411, 0x841D, 0x8429, 0x8D0E)
    for address in keyboard_reads:
        patch(ram, address, b"\xed\x78", b"\xdf\x00")
    # The Spectrum beeper and BASIC script printer are replaced by the MSX layer.
    patch(ram, 0x8B4A, b"\x3a", b"\xc9")
    patch(ram, 0x8B80, b"\xe6", b"\xc9")
    patch(ram, 0x8DEA, b"\xcd\x01\x16", b"\x00\x00\x00")
    patch(ram, 0x8DF9, b"\xcd\x28\x1a", b"\x00\x00\x00")
    # Any printable RST 10h falls into a harmless routine in the MSX layer.
    patch(ram, 0x84C4, b"\xcd\x00\x81", b"\xcd\x00\x00")

    # Reuse the byte-for-byte attribute and keyboard maps from the 3D Pool
    # MSX1 layer, generated here to keep this project self contained.
    zx = [1, 4, 6, 13, 12, 7, 10, 14]
    bright = [1, 5, 8, 13, 2, 7, 11, 15]
    def keypos(key: str) -> int:
        if key.isdigit():
            number = int(key)
            row, bit = ((0, number) if number < 8 else (1, number - 8))
        elif len(key) == 1:
            if key in "AB":
                row, bit = 2, 6 + "AB".index(key)
            else:
                offset = ord(key) - ord("C")
                row, bit = 3 + offset // 8, offset % 8
        else:
            row, bit = {"CAPS": (6, 0), "SYM": (6, 1), "ENTER": (7, 7), "SPACE": (8, 0)}[key]
        return row * 16 + bit
    keyboard = [["CAPS", "Z", "X", "C", "V"], list("ASDFG"), list("QWERT"),
                list("12345"), list("09876"), list("POIUY"),
                ["ENTER", "L", "K", "J", "H"], ["SPACE", "SYM", "M", "N", "B"]]
    lines = ["; Generated by tools/build.py", "keymap:"]
    for row in keyboard:
        lines.append(" db " + ",".join(f"0{keypos(k):02X}h" for k in row))
    lines += ["bordcol: db " + ",".join(str(x) for x in zx),
              " ds (($+255) and 0FF00h)-$", "attr2col:"]
    for a in range(0, 256, 16):
        values = []
        for value in range(a, a + 16):
            palette = bright if value & 0x40 else zx
            # Gameplay only: replace Spectrum white with MSX yellow (10).
            # Preserve ink/paper polarity and other colours. Static HUD and
            # menus have their own colour tables and retain their artwork.
            ink, paper = value & 7, (value >> 3) & 7
            foreground = 10 if ink == 7 else palette[ink]
            background = 10 if paper == 7 else palette[paper]
            values.append(f"0{(foreground << 4 | background):02X}h")
        lines.append(" db " + ",".join(values))
    (SRC / "tablas.inc").write_text("\n".join(lines) + "\n")

    # Extract the original script's sound commands. Script control bytes may
    # carry parameters above 127, so skip those before collecting notes.
    scripts = bytes(ram[0x9000:0x9800]).split(b"\xff")
    sounds = ["; Original Ant Attack script notes, extracted from the snapshot", "sound_ptrs:"]
    sounds += [" dw sound_seq_" + str(i) for i in range(1, 18)]
    intro_notes = []
    rescue_notes = []
    defeat_notes = []
    for i in range(1, 18):
        script = scripts[i]
        notes = []
        skip = 0
        for value in script:
            if skip:
                skip -= 1
            elif value == 0x16:
                skip = 2
            elif value in (0x7D, 0x7E, 0x10, 0x11, 0x12, 0x13):
                skip = 1
            elif value >= 0x80:
                notes.append(value)
        sounds.append(f"sound_seq_{i}: db " + ",".join([*(f"0{v:02X}h" for v in notes), "0"]))
        if i in (1, 2):
            intro_notes.extend(notes)
        if i == 13:
            rescue_notes = notes
        if i == 12:
            defeat_notes = notes
    sounds.append("sound_seq_intro: db " + ",".join([*(f"0{v:02X}h" for v in intro_notes), "0"]))
    sounds.append("sound_seq_rescue: db " + ",".join([*(f"0{v:02X}h" for v in rescue_notes[:14]), "0"]))
    pickup_notes = [defeat_notes[i] for i in (3, 4, 5, 7, 8, 10)]
    sounds.append("sound_seq_pickup: db " + ",".join([*(f"0{v:02X}h" for v in pickup_notes), "0"]))
    def basic_period(pitch: int) -> int:
        hz = 261.625565 * 2 ** (pitch / 12)
        return max(1, round(1789772.5 / (16 * hz)))

    def basic_sequence(name: str, notes: list[tuple[int, int]]) -> None:
        data = []
        for pitch, frames in notes:
            period = basic_period(pitch)
            data.extend((period & 255, period >> 8, frames))
        data.append(255)
        sounds.append(name + ": db " + ",".join(str(value) for value in data))

    # BASIC 3110: five cycles of four 50 ms notes at pitch 1 followed by
    # four at pitch 0. Alternating 2/3 VBlanks preserves the 50 ms average.
    # BASIC 3120: a 21-note 20 ms rising sweep, pitches 0..60 step 3.
    title_notes = [(1 if j < 4 else 0, 2 if (cycle * 8 + j) % 2 == 0 else 3)
                   for cycle in range(5) for j in range(8)]
    title_notes += [(pitch, 1) for pitch in range(0, 61, 3)]
    basic_sequence("sound_basic_title", title_notes)
    # BASIC 3220: 200 ms descending tones after time runs out.
    basic_sequence("sound_basic_timeout", [(pitch, 10) for pitch in range(40, -1, -3)])
    # The script interpreter at 8E45 masks each note with 0Fh before calling
    # 8B80. Only the first 16 pairs are musical periods; higher pairs overlap
    # executable code and must never be used for the script melodies.
    periods = []
    frames = []
    for i in range(16):
        delay, pulses = ram[0x8BB1 + 2*i:0x8BB3 + 2*i]
        half_wave_cycles = 84 + 14 * (delay or 256)
        periods.append(max(1, round(1789772.5 * half_wave_cycles / 28000000)))
        frames.append(max(1, round((pulses or 256) * half_wave_cycles / 70000)))
    sounds.append("sound_periods: dw " + ",".join(map(str, periods)))
    sounds.append("sound_frames: db " + ",".join(map(str, frames)))
    (SRC / "sound.inc").write_text("\n".join(sounds) + "\n")

    symbols = assemble("capa.asm", "capa.bin", "capa.sym")
    (ROOT / "tools" / "test_syms.tcl").write_text("".join(
        f"set {name} {symbols[name]}\n" for name in (
            "level_number", "player_sex", "score", "rescue_variant",
            "message_id", "message_dirty", "message_timer", "game_active",
            "control_keys", "rebind_index", "keymap", "reset_requested",
            "sound_ptr", "sound_count", "timer_extra_phase",
            "sound_intro", "sound_ready", "sound_event")))
    hook = symbols["game_screen_hook"]
    patch(ram, 0x84C4, b"\xcd\x00\x00", bytes((0xCD, hook & 255, hook >> 8)))
    sound_hook = symbols["sound_event"]
    patch(ram, 0x8E02, b"\x57\xdd\xe5", bytes((0xC3, sound_hook & 255, sound_hook >> 8)))
    timer_hook = symbols["game_timer_hook"]
    patch(ram, 0x8E98, b"\xcd\xd0\x8d", bytes((0xCD, timer_hook & 255, timer_hook >> 8)))
    move_hook = symbols["msx_player_move"]
    patch(ram, 0x82CB, b"\xcd\xd0\x89", bytes((0xCD, move_hook & 255, move_hook >> 8)))
    camera_hook = symbols["msx_draw_view"]
    depth_hook = symbols["msx_depth_layers"]
    patch(ram, 0x84A3, b"\xcd\xb0\x81", bytes((0xCD, depth_hook & 255, depth_hook >> 8)))
    patch(ram, 0x84A0, b"\xcd\xb0\x83", bytes((0xCD, camera_hook & 255, camera_hook >> 8)))
    patch(ram, 0x84B5, b"\xcd\x60\x84", b"\x00\x00\x00")
    input_hook = symbols["msx_control_input"]
    patch(ram, 0x8060, b"\x01\xfe\xfe", bytes((0xC3, input_hook & 255, input_hook >> 8)))
    grenade_hook = symbols["grenade_start"]
    patch(ram, 0x8D1F, b"\x32\x2E\xB4", bytes((0xC3, grenade_hook & 255, grenade_hook >> 8)))
    (SRC / "capa_syms.inc").write_text("".join(
        f"{name} equ 0{symbols[name]:04X}h\n" for name in ("L_start", "L_RAMV", "L_CARTV")))
    assemble("arranque.asm", "arranque.bin", "arranque.sym")
    bootstrap = (SRC / "arranque.bin").read_bytes()
    if len(bootstrap) > 0x4000:
        raise ValueError(f"Bootstrap too large: {len(bootstrap)}")
    rom = bootstrap.ljust(0x4000, b"\x00") + bytes(ram[0x4000:])
    if len(rom) != 0x10000:
        raise ValueError(len(rom))
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_bytes(rom)
    print(f"{OUT} ({len(rom)} bytes); layer ends at {symbols['L_END']:04X}")


if __name__ == "__main__":
    main()
